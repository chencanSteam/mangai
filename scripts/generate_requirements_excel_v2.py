def set_cell_style(cell, align="left"):
    cell.font = NORMAL_FONT
    cell.alignment = Alignment(horizontal=align, vertical="center", wrap_text=True)
    cell.border = BORDER

def auto_width(ws, min_width=10, max_width=60):
    for col in ws.columns:
        max_length = 0
        col_letter = get_column_letter(col[0].column)
        for cell in col:
            try:
                val = str(cell.value) if cell.value else ""
                lines = val.split("\n")
                for line in lines:
                    max_length = max(max_length, len(line))
            except:
                pass
        adjusted = min(max(min_width, max_length + 2), max_width)
        ws.column_dimensions[col_letter].width = adjusted

def merge_same_column(ws, col_idx, start_row, end_row, style_fn):
    """合并指定列中内容相同的连续单元格"""
    if start_row >= end_row:
        return
    r = start_row
    while r <= end_row:
        val = ws.cell(row=r, column=col_idx).value
        if val is None or val == "":
            r += 1
            continue
        end = r
        while end + 1 <= end_row and ws.cell(row=end + 1, column=col_idx).value == val:
            end += 1
        if end > r:
            ws.merge_cells(start_row=r, start_column=col_idx, end_row=end, end_column=col_idx)
            style_fn(ws.cell(row=r, column=col_idx))
        r = end + 1

