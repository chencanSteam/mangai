def main():
    wb = openpyxl.Workbook()
    if "Sheet" in wb.sheetnames:
        del wb["Sheet"]
    
    ws = wb.create_sheet(title="需求清单", index=0)
    
    # 写入表头
    headers = ("模块", "页面", "功能点", "功能描述", "闭环检查", "缺口说明")
    for c_idx, h in enumerate(headers, 1):
        cell = ws.cell(row=1, column=c_idx, value=h)
        set_header_style(cell)
    
    # 写入数据
    for r_idx, row in enumerate(ROWS[1:], 2):
        for c_idx, value in enumerate(row, 1):
            cell = ws.cell(row=r_idx, column=c_idx, value=value)
            if c_idx == 5:  # 闭环检查列
                if value == "已闭环":
                    set_ok_style(cell)
                elif value == "有缺口":
                    set_warn_style(cell)
                else:
                    set_cell_style(cell, "center")
            elif c_idx == 6:  # 缺口说明列
                if row[4] == "有缺口":
                    set_gap_style(cell)
                else:
                    set_cell_style(cell)
            else:
                set_cell_style(cell)
    
    # 合并模块列
    merge_same_column(ws, 1, 2, len(ROWS), set_module_style)
    
    # 合并页面列（在同一模块内）
    r = 2
    while r <= len(ROWS):
        module_val = ws.cell(row=r, column=1).value
        page_val = ws.cell(row=r, column=2).value
        if not page_val:
            r += 1
            continue
        end = r
        while (end + 1 <= len(ROWS) and 
               ws.cell(row=end+1, column=1).value == module_val and 
               ws.cell(row=end+1, column=2).value == page_val):
            end += 1
        if end > r:
            ws.merge_cells(start_row=r, start_column=2, end_row=end, end_column=2)
            set_page_style(ws.cell(row=r, column=2))
        r = end + 1
    
    ws.freeze_panes = "A2"
    auto_width(ws)
    
    # 设置闭环检查列宽小一些
    ws.column_dimensions["E"].width = 12
    
    wb.save(OUTPUT_PATH)
    print(f"已生成: {OUTPUT_PATH}")
    
    ok_count = sum(1 for r in ROWS[1:] if r[4] == "已闭环")
    gap_count = sum(1 for r in ROWS[1:] if r[4] == "有缺口")
    print(f"共 {len(ROWS)-1} 条需求，已闭环 {ok_count} 条，有缺口 {gap_count} 条")

if __name__ == "__main__":
    main()
